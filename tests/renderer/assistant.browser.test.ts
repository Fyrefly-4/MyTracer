import { expect, test } from '@playwright/test'
const path = '/tests/renderer/assistant-harness.html'
test('overlay preserves underlying draft and restores focus; candidates need separate confirmation', async ({
  page
}) => {
  await page.goto(path)
  await page.getByLabel('原笔记').fill('合成笔记：书桌整理了一半，其他日期没有记录。'.repeat(8))
  const trigger = page.getByRole('button', { name: '帮我整理', exact: true })
  const pane = page.getByTestId('underlying-pane')
  await pane.evaluate((element) => {
    element.scrollTop = 100
  })
  await trigger.click()
  const paneScroll = await pane.evaluate((element) => element.scrollTop)
  expect(paneScroll).toBeGreaterThan(0)
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('继续聊聊').fill('整理一句简述')
  await dialog.getByRole('button', { name: '发送', exact: true }).click()
  await expect(dialog.getByText('整理完成；候选尚未写入正式记录。', { exact: true })).toBeVisible()
  await page.screenshot({ path: '.tmp/assistant-browser-results/desktop.png' })
  await dialog.getByRole('button', { name: '仅填入编辑草稿' }).click()
  await expect(dialog.getByRole('status')).toContainText('未保存草稿')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(trigger).toBeFocused()
  expect(await pane.evaluate((element) => element.scrollTop)).toBe(paneScroll)
  await expect(page.getByLabel('原笔记')).toHaveValue(
    '合成笔记：书桌整理了一半，其他日期没有记录。'.repeat(8)
  )
  expect(await page.getByLabel('简述草稿').inputValue()).toContain('整理了书桌左侧')
  await page.getByRole('button', { name: '接上上次', exact: true }).click()
  await dialog.getByLabel('继续聊聊').fill('时间少一点呢？')
  await dialog.getByRole('button', { name: '发送', exact: true }).click()
  await dialog.getByRole('button', { name: '预览：创建行动（不设为下一步）', exact: true }).click()
  await expect(dialog.getByRole('region', { name: '正式写入预览' })).toBeVisible()
  await dialog.getByRole('button', { name: '确认：创建行动（不设为下一步）', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('已确认保存')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '接上上次', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('没有重新发送请求')
  await expect(dialog.getByLabel('对话').getByText('时间少一点呢？', { exact: true })).toBeVisible()
})
test('narrow overlay and settings disclose simulation and unknown capabilities', async ({
  page
}) => {
  await page.setViewportSize({ width: 420, height: 800 })
  await page.goto(path)
  await page.getByRole('button', { name: '测试已保存连接' }).click()
  await expect(page.getByRole('status')).toContainText('流式：未知；工具：未知')
  await page.getByRole('button', { name: '选定内容回顾', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('继续聊聊').fill('回顾选定事实')
  await dialog.getByRole('button', { name: '发送', exact: true }).click()
  await expect(dialog.getByLabel('确认的进展')).toHaveValue('整理了一次书桌。')
  const box = await dialog.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(420)
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.y + box!.height).toBeLessThanOrEqual(800)
  await page.screenshot({ path: '.tmp/assistant-browser-results/narrow.png', fullPage: false })
  await dialog.getByRole('button', { name: '仅填入编辑草稿' }).click()
  await expect(dialog.getByRole('status')).toContainText('未保存草稿')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(page.getByLabel('复盘进展草稿')).toHaveValue('整理了一次书桌。')
  await expect(page.getByLabel('复盘阻碍草稿')).toHaveValue('右侧仍需整理；未记录的日期保持未知。')
  await expect(page.getByLabel('复盘调整草稿')).toHaveValue('下次只整理右侧的一小块。')
})

test('unsent composer survives hide and blocks install; clearing and saving release dirty flags', async ({
  page
}) => {
  await page.goto(path)
  const probe = async (dirty: boolean): Promise<void> => {
    await page.getByRole('button', { name: '检查安装草稿' }).click()
    await expect(page.getByTestId('install-dirty')).toHaveText(String(dirty))
  }
  await probe(false)
  await page.getByRole('button', { name: '帮我整理', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('继续聊聊').fill('合成未发送文本')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await probe(true)
  await page.getByRole('button', { name: '接上上次', exact: true }).click()
  await expect(dialog.getByLabel('继续聊聊')).toHaveValue('')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await probe(true)
  await page.getByRole('button', { name: '帮我整理', exact: true }).click()
  await expect(dialog.getByLabel('继续聊聊')).toHaveValue('合成未发送文本')
  await dialog.getByLabel('继续聊聊').fill('')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await probe(false)
  await page.getByRole('button', { name: '选定内容回顾', exact: true }).click()
  await dialog.getByLabel('继续聊聊').fill('另一入口的未发送草稿')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '帮我整理', exact: true }).click()
  await expect(dialog.getByLabel('继续聊聊')).toHaveValue('')
  await dialog.getByRole('button', { name: '清空所有未发送输入' }).click()
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await probe(false)
  const model = page.getByLabel('模型名称')
  const original = await model.inputValue()
  await model.fill('synthetic-new-model')
  await page.getByRole('button', { name: '切换设置可见' }).click()
  await probe(true)
  await page.getByRole('button', { name: '切换设置可见' }).click()
  await expect(model).toHaveValue('synthetic-new-model')
  await model.fill(original)
  await probe(false)
  await page.getByLabel('API Key').fill('synthetic-unsaved-key')
  await probe(true)
  await page.getByLabel('API Key').fill('')
  await probe(false)
  await model.fill('synthetic-new-model')
  await page.getByRole('button', { name: '保存配置', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('配置已保存')
  await probe(false)
  await page.getByRole('button', { name: '测试已保存连接' }).click()
  await probe(false)
})
